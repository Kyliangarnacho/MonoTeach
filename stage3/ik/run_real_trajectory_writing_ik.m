function run = run_real_trajectory_writing_ik(jsonPath)
%RUN_REAL_TRAJECTORY_WRITING_IK Evaluate real C920 triangle with Writing IK.
%
% This pipeline keeps the WorkspaceTrajectory source immutable, reuses the
% Stage 3.1 mapping helper, and compares frozen Position-Only solver behavior
% with the independent Stage 3.3 XYZ + body5-local-Z Writing solver.

    if nargin < 1 || isempty(jsonPath)
        jsonPath = default_real_workspace_trajectory_path();
    end
    jsonPath = char(string(jsonPath));
    if ~isfile(jsonPath)
        error( ...
            'MonoTeach:MissingRealWritingWorkspaceTrajectory', ...
            'WorkspaceTrajectory JSON does not exist: %s', jsonPath);
    end

    workspaceTrajectory = load_workspace_trajectory(jsonPath);
    baselineTaskPlaneConfig = default_task_plane_config();
    candidateConfig = default_writing_candidate_config();
    candidateTaskPlaneConfig = build_writing_candidate_task_plane_config( ...
        baselineTaskPlaneConfig, candidateConfig);
    taskTrajectory = workspace_to_task_trajectory( ...
        workspaceTrajectory, candidateTaskPlaneConfig);
    preIkSegmentSet = build_preik_segments(taskTrajectory);

    robot = build_legacy_robot();
    ikConfig = default_ik_config();
    writingPostureConfig = default_writing_posture_config();
    % Same real samples and same candidate mapping; only orientation policy
    % differs. The accepted Stage 3.2 Position-Only solver stays unmodified.
    positionAnchor = solve_anchor_ik(robot, candidateTaskPlaneConfig, ikConfig);
    positionResultSet = solve_ik_segments( ...
        robot, preIkSegmentSet, positionAnchor, ikConfig);
    positionSummary = summarize_ik_continuity(positionResultSet);
    positionSummary.total_preik_samples = ...
        preIkSegmentSet.summary.eligible_sample_count;
    positionOnlySeedLookup = build_position_only_seed_lookup(positionResultSet);

    centerSeed = resolve_writing_candidate_center_seed( ...
        robot, candidateTaskPlaneConfig, ikConfig, ...
        writingPostureConfig, candidateConfig);

    % Controlled A/B: legacy policy never reads point-specific Position-Only
    % q values.  The new policy adds them as deterministic recovery seeds.
    oldPolicy = default_writing_recovery_policy('legacy_previous_then_center');
    oldWritingResultSet = solve_writing_ik_segments( ...
        robot, preIkSegmentSet, centerSeed, candidateTaskPlaneConfig, ...
        writingPostureConfig, candidateConfig, positionOnlySeedLookup, oldPolicy);
    recoveryPolicy = default_writing_recovery_policy('position_only_recovery');
    writingResultSet = solve_writing_ik_segments( ...
        robot, preIkSegmentSet, centerSeed, candidateTaskPlaneConfig, ...
        writingPostureConfig, candidateConfig, positionOnlySeedLookup, recoveryPolicy);
    writingSummary = writingResultSet.summary;
    writingSummary.total_preik_samples = ...
        preIkSegmentSet.summary.eligible_sample_count;
    backwardRescue = rescue_writing_ik_backward( ...
        robot, preIkSegmentSet, writingResultSet, candidateTaskPlaneConfig, ...
        writingPostureConfig, candidateConfig);
    rescuedWritingResultSet = backwardRescue.result_set;
    rescuedWritingSummary = backwardRescue.summary;
    rescuedWritingSummary.total_preik_samples = ...
        preIkSegmentSet.summary.eligible_sample_count;
    oldWritingSummary = oldWritingResultSet.summary;
    oldWritingSummary.total_preik_samples = ...
        preIkSegmentSet.summary.eligible_sample_count;

    run = struct();
    run.json_path = jsonPath;
    run.workspace_trajectory = workspaceTrajectory;
    run.candidate_config = candidateConfig;
    run.candidate_task_plane_config = candidateTaskPlaneConfig;
    run.task_trajectory = taskTrajectory;
    run.preik_segment_set = preIkSegmentSet;
    run.center_writing_seed = centerSeed;
    run.position_only_seed_lookup = positionOnlySeedLookup;
    run.writing_old_policy_result_set = oldWritingResultSet;
    run.writing_old_policy_summary = oldWritingSummary;
    run.writing_result_set = writingResultSet;
    run.writing_backward_rescue = backwardRescue;
    run.writing_rescued_result_set = rescuedWritingResultSet;
    run.writing_rescued_summary = rescuedWritingSummary;
    run.position_only_anchor = positionAnchor;
    run.position_only_result_set = positionResultSet;
    run.writing_summary = writingSummary;
    run.position_only_summary = positionSummary;
    run.ab_comparison = build_ab_comparison(positionSummary, writingSummary);
    run.writing_recovery_ab_comparison = build_recovery_ab_comparison( ...
        oldWritingSummary, writingSummary);
    run.forward_backward_rescue_ab_comparison = ...
        build_forward_backward_rescue_ab_comparison( ...
            writingSummary, rescuedWritingSummary, backwardRescue);
end


function comparison = build_forward_backward_rescue_ab_comparison( ...
        forwardSummary, rescuedSummary, rescue)

    comparison = struct();
    comparison.forward = struct( ...
        'success_point_count', forwardSummary.success_point_count, ...
        'failure_count', forwardSummary.failure_count, ...
        'success_rate', forwardSummary.ik_success_rate, ...
        'success_segment_count', forwardSummary.ik_success_segment_count, ...
        'max_joint_step_rad', forwardSummary.overall_max_joint_step, ...
        'minimum_joint_limit_margin', forwardSummary.minimum_joint_limit_margin);
    comparison.forward_plus_backward_rescue = struct( ...
        'success_point_count', rescuedSummary.success_point_count, ...
        'failure_count', rescuedSummary.failure_count, ...
        'success_rate', rescuedSummary.ik_success_rate, ...
        'success_segment_count', rescuedSummary.ik_success_segment_count, ...
        'max_joint_step_rad', rescuedSummary.overall_max_joint_step, ...
        'minimum_joint_limit_margin', rescuedSummary.minimum_joint_limit_margin, ...
        'remaining_failure_reason_distribution', ...
            rescuedSummary.failure_reason_distribution);
    comparison.backward_rescued_source_indices = ...
        rescue.backward_rescued_source_indices;
end


function comparison = build_recovery_ab_comparison(oldSummary, newSummary)

    comparison = struct();
    comparison.old_policy = summarize_recovery_policy(oldSummary);
    comparison.new_policy = summarize_recovery_policy(newSummary);
    comparison.success_rate_delta = newSummary.ik_success_rate - ...
        oldSummary.ik_success_rate;
    comparison.success_point_count_delta = newSummary.success_point_count - ...
        oldSummary.success_point_count;
end


function summary = summarize_recovery_policy(source)

    summary = struct( ...
        'success_point_count', source.success_point_count, ...
        'failure_count', source.failure_count, ...
        'success_rate', source.ik_success_rate, ...
        'success_segment_count', source.ik_success_segment_count, ...
        'accepted_seed_provenance_distribution', ...
            source.accepted_seed_provenance_distribution, ...
        'failure_reason_distribution', source.failure_reason_distribution, ...
        'mean_fk_position_error_m', source.mean_fk_position_error_m, ...
        'max_fk_position_error_m', source.max_fk_position_error_m, ...
        'mean_tool_direction_error_deg', source.mean_tool_direction_error_deg, ...
        'max_tool_direction_error_deg', source.max_tool_direction_error_deg, ...
        'max_joint_step_rad', source.overall_max_joint_step, ...
        'minimum_joint_limit_margin', source.minimum_joint_limit_margin);
end


function jsonPath = default_real_workspace_trajectory_path()

    stage3Dir = fileparts(fileparts(mfilename('fullpath')));
    repoRoot = fileparts(stage3Dir);
    candidates = dir(fullfile( ...
        repoRoot, 'data', 'workspace_trajectories', ...
        '*_workspace_2d_*.json'));
    if numel(candidates) ~= 1
        error( ...
            'MonoTeach:AmbiguousRealWritingWorkspaceTrajectory', ...
            ['Expected exactly one real C920 WorkspaceTrajectory under ' ...
             'data/workspace_trajectories; pass jsonPath explicitly.']);
    end
    jsonPath = fullfile(candidates(1).folder, candidates(1).name);
end


function comparison = build_ab_comparison(positionSummary, writingSummary)

    comparison = struct();
    comparison.position_only = struct( ...
        'success_rate', positionSummary.ik_success_rate, ...
        'mean_fk_position_error_m', positionSummary.mean_fk_position_error_m, ...
        'max_fk_position_error_m', positionSummary.max_fk_position_error_m, ...
        'max_joint_step_rad', positionSummary.overall_max_joint_step, ...
        'minimum_joint_limit_margin', ...
            positionSummary.minimum_joint_limit_margin);
    comparison.writing_posture = struct( ...
        'success_rate', writingSummary.ik_success_rate, ...
        'mean_fk_position_error_m', writingSummary.mean_fk_position_error_m, ...
        'max_fk_position_error_m', writingSummary.max_fk_position_error_m, ...
        'max_joint_step_rad', writingSummary.overall_max_joint_step, ...
        'minimum_joint_limit_margin', ...
            writingSummary.minimum_joint_limit_margin, ...
        'mean_tool_direction_error_deg', ...
            writingSummary.mean_tool_direction_error_deg, ...
        'max_tool_direction_error_deg', ...
            writingSummary.max_tool_direction_error_deg);
end
