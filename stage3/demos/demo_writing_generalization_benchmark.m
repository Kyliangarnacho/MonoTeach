function demo = demo_writing_generalization_benchmark()
%DEMO_WRITING_GENERALIZATION_BENCHMARK Run and display frozen gate metrics.

    benchmark = run_writing_generalization_benchmark();
    tableFields = { ...
        'trajectory_name', 'path_length_m', 'resampled_point_count', ...
        'position_only_success_rate', 'writing_success_rate', ...
        'accepted_sampled_coverage_fraction', 'ik_success_segment_count', ...
        'max_joint_step_rad', 'minimum_joint_limit_margin', ...
        'mean_position_error_m', 'mean_direction_error_deg'};
    summaryTable = struct2table(benchmark.summary_table);
    summaryTable = summaryTable(:, tableFields);
    disp(summaryTable);
    demo = struct('benchmark', benchmark, 'summary_table', summaryTable);
end
