function writing = synthetic_writing_results_for_continuous(robot, continuous)

    writingSegments = repmat(struct('results', struct([])), 1, ...
        numel(continuous.segments));
    for segmentIndex = 1:numel(continuous.segments)
        segment = continuous.segments(segmentIndex);
        results = repmat(struct('source_index', NaN, 'target_xyz_m', NaN(1,3)), ...
            1, size(segment.waypoint_q_rad, 1));
        for pointIndex = 1:numel(results)
            pose = getTransform(robot, segment.waypoint_q_rad(pointIndex, :), 'body5');
            results(pointIndex).source_index = segment.source_indices(pointIndex);
            results(pointIndex).target_xyz_m = pose(1:3, 4)';
        end
        writingSegments(segmentIndex).results = results;
    end
    writing = struct('segments', writingSegments);
end


function [continuous, writing, taskPlane, candidate] = ...
        synthetic_continuous_writing_geometry_input(robot, baselineTaskPlane)

    q0 = homeConfiguration(robot);
    q1 = q0;
    q1(1) = q1(1) + 0.1;
    qMid = (q0 + q1) / 2;
    pose0 = getTransform(robot, q0, 'body5');
    pose1 = getTransform(robot, q1, 'body5');
    xyz0 = pose0(1:3, 4)';
    xyz1 = pose1(1:3, 4)';
    provenanceOne = {struct('source_index', 101); struct('source_index', 102)};
    provenanceTwo = {struct('source_index', 201); struct('source_index', 202)};
    segmentOne = synthetic_continuous_geometry_segment( ...
        1, [101, 102], [q0; qMid; q1], [0; 0.05; 0.1], ...
        [0; 0.1], provenanceOne);
    segmentTwo = synthetic_continuous_geometry_segment( ...
        2, [201, 202], [q1; qMid; q0], [0; 0.05; 0.1], ...
        [0; 0.1], provenanceTwo);
    continuous = struct('artifact_type', 'ContinuousJointTrajectory', ...
        'segments', [segmentOne, segmentTwo]);
    writingOne = struct('results', [ ...
        synthetic_writing_target_result(101, xyz0), ...
        synthetic_writing_target_result(102, xyz1)]);
    writingTwo = struct('results', [ ...
        synthetic_writing_target_result(201, xyz1), ...
        synthetic_writing_target_result(202, xyz0)]);
    writing = struct('segments', [writingOne, writingTwo]);
    candidate = default_writing_candidate_config();
    taskPlane = build_writing_candidate_task_plane_config( ...
        baselineTaskPlane, candidate);
end


