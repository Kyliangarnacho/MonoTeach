function testMultiStartDiagnosticRetainsTrialAndSummarySemantics(testCase)

    diagnosticConfig = default_writing_anchor_diagnostic_config();
    diagnosticConfig.random_seed_count = 0;
    diagnosticConfig.solver_algorithms = {'LevenbergMarquardt'};
    diagnostic = diagnose_writing_anchor_multistart( ...
        testCase.TestData.robot, ...
        testCase.TestData.taskPlaneConfig, ...
        testCase.TestData.ikConfig, ...
        testCase.TestData.writingPostureConfig, ...
        diagnosticConfig);

    requiredTrialFields = { ...
        'initial_q', ...
        'solver_algorithm', ...
        'candidate_q', ...
        'position_error_m', ...
        'tool_direction_error_rad', ...
        'within_joint_limits', ...
        'joint_limit_margin', ...
        'accepted'};
    requiredSummaryFields = { ...
        'trials_count', ...
        'accepted_count', ...
        'best_position_error_m', ...
        'best_direction_error_rad', ...
        'best_combined_trial_index', ...
        'has_simultaneous_position_and_direction_solution'};

    for runIndex = 1:numel(diagnostic.runs)
        run = diagnostic.runs(runIndex);
        verifyTrue(testCase, all(isfield(run, requiredSummaryFields)));
        verifyEqual(testCase, run.trials_count, 2);
        verifyEqual(testCase, run.accepted_count, sum([run.trials.accepted]));
        for trialIndex = 1:numel(run.trials)
            trial = run.trials(trialIndex);
            verifyTrue(testCase, all(isfield(trial, requiredTrialFields)));
            verifySize(testCase, trial.initial_q, [1, 5]);
            if trial.accepted
                verifyLessThanOrEqual( ...
                    testCase, trial.position_error_m, ...
                    testCase.TestData.writingPostureConfig.position_tolerance_m);
                verifyLessThanOrEqual( ...
                    testCase, trial.tool_direction_error_rad, ...
                    testCase.TestData.writingPostureConfig.aiming_angular_tolerance_rad);
                verifyTrue(testCase, trial.within_joint_limits);
            end
        end
    end
end


