        comparison.previous_success_seed.max_abs_joint_step_rad));
    verifyTrue(testCase, isfinite( ...
        comparison.anchor_seed.max_abs_joint_step_rad));
end


function limits = five_joint_limits(robot)

    limits = zeros(5, 2);

    for i = 1:5
        limits(i, :) = robot.Bodies{i}.Joint.PositionLimits;
    end
end


function segmentSet = synthetic_failure_segment_set(robot, ikConfig)

    qOne = homeConfiguration(robot);
    qTwo = deg2rad([10, 100, -10, 100, 10]);
    qThree = deg2rad([-10, 80, 10, 110, -10]);
    targetOne = getTransform(robot, qOne, ikConfig.end_effector);
    targetTwo = getTransform(robot, qTwo, ikConfig.end_effector);
    targetThree = getTransform(robot, qThree, ikConfig.end_effector);

    samples = [ ...
        synthetic_sample(0.0, targetOne(1:3, 4)'), ...
        synthetic_sample(100.0, targetTwo(1:3, 4)'), ...
        synthetic_sample(200.0, [10.0, 10.0, 10.0]), ...
        synthetic_sample(300.0, targetThree(1:3, 4)')];

    segment = struct( ...
        'source_indices', [11, 12, 13, 14], ...
        'samples', samples);
    segmentSet = struct( ...
        'coordinate_frame', 'robot_base', ...
        'units', 'm', ...
        'segments', segment);
end


function segmentSet = independent_reachable_segment_set(robot, ikConfig)

    qOne = homeConfiguration(robot);
    qTwo = deg2rad([15, 95, -15, 105, 15]);
    targetOne = getTransform(robot, qOne, ikConfig.end_effector);
    targetTwo = getTransform(robot, qTwo, ikConfig.end_effector);

    firstSegment = struct( ...
        'source_indices', 21, ...
        'samples', synthetic_sample(0.0, targetOne(1:3, 4)'));
    secondSegment = struct( ...
        'source_indices', 22, ...
        'samples', synthetic_sample(100.0, targetTwo(1:3, 4)'));
    segmentSet = struct( ...
        'coordinate_frame', 'robot_base', ...
        'units', 'm', ...
        'segments', [firstSegment, secondSegment]);
end


function sample = synthetic_sample(tMs, xyzM)

    sample = struct( ...
        't_ms', tMs, ...
        'valid', true, ...
        'inside_workspace', true, ...
        'x_m', xyzM(1), ...
        'y_m', xyzM(2), ...
        'z_m', xyzM(3));
end
