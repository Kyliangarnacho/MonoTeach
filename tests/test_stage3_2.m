function testContinuitySummaryMatchesCanonicalDiagnostics(testCase)

    robot = testCase.TestData.robot;
    ikConfig = testCase.TestData.ikConfig;
    anchorResult = solve_anchor_ik( ...
        robot, ...
        testCase.TestData.taskPlaneConfig, ...
        ikConfig);
    ikResultSet = solve_ik_segments( ...
        robot, ...
        synthetic_failure_segment_set(robot, ikConfig), ...
        anchorResult, ...
        ikConfig);
    resultSetBefore = ikResultSet;

    continuity = summarize_ik_continuity(ikResultSet);
    firstSuccessSegment = ikResultSet.segments(1);
    secondSuccessSegment = ikResultSet.segments(2);
    pointResults = [ ...
        firstSuccessSegment.results, ...
        secondSuccessSegment.results];
    expectedErrors = [pointResults.position_error_m];
    expectedMargins = vertcat(pointResults.joint_limit_margin);
    expectedDelta = firstSuccessSegment.results(2).delta_q;
    [expectedMaxStep, expectedJointIndex] = max(abs(expectedDelta));
    [expectedMinimumMargin, marginFlatIndex] = min(expectedMargins, [], 'all');
    [marginPointIndex, expectedClosestJointIndex] = ind2sub( ...
        size(expectedMargins), ...
        marginFlatIndex);

    verifyEqual(testCase, ikResultSet, resultSetBefore);
    verifyEqual(testCase, continuity.success_point_count, 3);
    verifyEqual(testCase, continuity.failure_count, 1);
    verifyEqual(testCase, continuity.ik_success_rate, 0.75, 'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.mean_fk_position_error_m, ...
        mean(expectedErrors), ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.max_fk_position_error_m, ...
        max(expectedErrors), ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.per_joint_max_abs_delta_q, ...
        abs(expectedDelta), ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.mean_abs_delta_q, ...
        mean(abs(expectedDelta), 'all'), ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.overall_max_joint_step, ...
        expectedMaxStep, ...
        'AbsTol', 1e-12);
    verifyEqual(testCase, continuity.largest_jump_source_index, 12);
    verifyEqual(testCase, continuity.largest_jump_joint_index, expectedJointIndex);
    verifyEqual( ...
        testCase, ...
        continuity.minimum_joint_limit_margin, ...
        expectedMinimumMargin, ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        continuity.closest_limit_joint_index, ...
        expectedClosestJointIndex);
    verifyEqual( ...
        testCase, ...
        continuity.closest_limit_source_index, ...
        pointResults(marginPointIndex).source_index);
end


function testSeedStrategyComparisonReportsBothPolicies(testCase)

    robot = testCase.TestData.robot;
    ikConfig = testCase.TestData.ikConfig;
    anchorResult = solve_anchor_ik( ...
        robot, ...
