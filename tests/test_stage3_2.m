function setupOnce(testCase)

    testFile = mfilename('fullpath');
    testsDir = fileparts(testFile);
    repoRoot = fileparts(testsDir);
    stage3Dir = fullfile(repoRoot, 'stage3');
    stage1Dir = fullfile(repoRoot, 'stage1');

    stage3Path = genpath(stage3Dir);
    addpath(stage3Path);
    addpath(stage1Dir);

    testCase.TestData.stage3Dir = stage3Dir;
    testCase.TestData.stage3Path = stage3Path;
    testCase.TestData.stage1Dir = stage1Dir;
    testCase.TestData.robot = build_legacy_robot();
    testCase.TestData.taskPlaneConfig = default_task_plane_config();
    testCase.TestData.ikConfig = default_ik_config();
end


function teardownOnce(testCase)

    rmpath(testCase.TestData.stage1Dir);
    rmpath(testCase.TestData.stage3Path);
end


function testDefaultConfigIsDeterministicPositionOnly(testCase)

    ikConfig = testCase.TestData.ikConfig;

    verifyEqual(testCase, ikConfig.weights, [0, 0, 0, 1, 1, 1]);
    verifyFalse(testCase, ikConfig.allow_random_restart);
end


function testAnchorIkReturnsCanonicalSuccessfulResult(testCase)

    robot = testCase.TestData.robot;
    ikConfig = testCase.TestData.ikConfig;
    result = solve_anchor_ik( ...
        robot, ...
        testCase.TestData.taskPlaneConfig, ...
        ikConfig);

    requiredFields = { ...
        'target_xyz_m', ...
        'seed_q', ...
        'q', ...
        'solver_status', ...
        'pose_error_norm', ...
        'fk_xyz_m', ...
        'position_error_m', ...
        'within_joint_limits', ...
        'joint_limit_margin', ...
        'source_index', ...
        't_ms', ...
        'delta_q'};
    verifyTrue(testCase, all(isfield(result, requiredFields)));

    qAnchor = result.q;
    verifySize(testCase, result.seed_q, [1, 5]);
    verifySize(testCase, qAnchor, [1, 5]);
    verifyTrue(testCase, all(isfinite(qAnchor)));
    verifyNotEmpty(testCase, result.solver_status);
    verifyTrue(testCase, isfinite(result.pose_error_norm));
    verifyTrue(testCase, all(isfinite(result.fk_xyz_m)));
    verifyLessThanOrEqual( ...
        testCase, ...
        result.position_error_m, ...
        ikConfig.position_error_tolerance_m);
    verifyTrue(testCase, result.within_joint_limits);
    verifyTrue(testCase, all(isfinite(result.joint_limit_margin)));
    verifyGreaterThanOrEqual(testCase, min(result.joint_limit_margin), 0.0);

    % The anchor is a stand-alone point, so trajectory provenance and
    % neighbour-to-neighbour delta evidence must not be invented yet.
    verifyEmpty(testCase, result.source_index);
    verifyEmpty(testCase, result.t_ms);
    verifyEmpty(testCase, result.delta_q);

    % Test recovered Cartesian position through FK, rather than trusting the
    % solver status or its internal pose norm as the external geometry check.
    fkPose = getTransform(robot, qAnchor, ikConfig.end_effector);
    verifyLessThanOrEqual( ...
        testCase, ...
        norm(fkPose(1:3, 4)' - result.target_xyz_m), ...
        ikConfig.position_error_tolerance_m);
end


function testKnownReachableTargetRecoversPositionNotJointVector(testCase)

    robot = testCase.TestData.robot;
    ikConfig = testCase.TestData.ikConfig;

    % This configuration is strictly inside all five Stage 1 joint ranges.
    qKnown = deg2rad([30, 60, -30, 120, 45]);
    knownPose = getTransform(robot, qKnown, ikConfig.end_effector);
    targetXYZM = knownPose(1:3, 4)';

    % Deliberately discard qKnown. Position-only IK can have multiple valid
    % joint solutions, so qRecovered == qKnown is neither required nor a
    % correct regression assertion. The required observable is recovered FK
    % XYZ at this known reachable target.
    seedQ = homeConfiguration(robot);
    homePose = getTransform(robot, seedQ, ikConfig.end_effector);
    targetPose = homePose;
    targetPose(1:3, 4) = targetXYZM';

    ik = inverseKinematics( ...
        'RigidBodyTree', robot, ...
        'SolverAlgorithm', ikConfig.solver_algorithm);
    solverParameters = ik.SolverParameters;
    solverParameters.AllowRandomRestart = ikConfig.allow_random_restart;
    ik.SolverParameters = solverParameters;

    [qRecovered, solutionInfo] = ik( ...
        ikConfig.end_effector, ...
        targetPose, ...
        ikConfig.weights, ...
        seedQ);
    qRecovered = reshape(qRecovered, 1, []);
    fkRecoveredPose = getTransform( ...
        robot, ...
        qRecovered, ...
        ikConfig.end_effector);
    fkXYZM = fkRecoveredPose(1:3, 4)';

    result = ik_result_contract( ...
        targetXYZM, ...
        seedQ, ...
        qRecovered, ...
        solutionInfo.Status, ...
        solutionInfo.PoseErrorNorm, ...
        fkXYZM, ...
        five_joint_limits(robot));

    verifySize(testCase, result.q, [1, 5]);
    verifyTrue(testCase, all(isfinite(result.q)));
    verifyTrue(testCase, isfinite(result.pose_error_norm));
    verifyLessThanOrEqual( ...
        testCase, ...
        result.position_error_m, ...
        ikConfig.position_error_tolerance_m);
    verifyTrue(testCase, result.within_joint_limits);
    verifyGreaterThanOrEqual(testCase, min(result.joint_limit_margin), 0.0);
end


function testContinuousIkSplitsFailuresAndResetsSeed(testCase)

    robot = testCase.TestData.robot;
    ikConfig = testCase.TestData.ikConfig;
    anchorResult = solve_anchor_ik( ...
        robot, ...
        testCase.TestData.taskPlaneConfig, ...
        ikConfig);
    segmentSet = synthetic_failure_segment_set(robot, ikConfig);
    segmentSetBefore = segmentSet;

    ikResultSet = solve_ik_segments( ...
        robot, ...
        segmentSet, ...
        anchorResult, ...
        ikConfig);

    verifyEqual(testCase, segmentSet, segmentSetBefore);
    verifyEqual(testCase, string(ikResultSet.coordinate_space), "joint");
    verifyEqual(testCase, string(ikResultSet.units), "rad");
    verifyEqual(testCase, ikResultSet.summary.preik_segment_count, 1);
    verifyEqual(testCase, ikResultSet.summary.ik_success_segment_count, 2);
    verifyEqual(testCase, ikResultSet.summary.success_point_count, 3);
    verifyEqual(testCase, ikResultSet.summary.failure_count, 1);

    firstSuccessSegment = ikResultSet.segments(1);
    secondSuccessSegment = ikResultSet.segments(2);
    failure = ikResultSet.failures(1);

    verifyEqual(testCase, firstSuccessSegment.source_indices, [11, 12]);
    verifyEqual(testCase, firstSuccessSegment.t_ms, [0.0, 100.0]);
    verifySize(testCase, firstSuccessSegment.q_rad, [2, 5]);
    verifyEqual( ...
        testCase, ...
        firstSuccessSegment.results(2).seed_q, ...
        firstSuccessSegment.results(1).q, ...
        'AbsTol', 1e-12);
    verifyEqual( ...
        testCase, ...
        firstSuccessSegment.results(2).delta_q, ...
        firstSuccessSegment.results(2).q - firstSuccessSegment.results(1).q, ...
        'AbsTol', 1e-12);
    verifyEmpty(testCase, firstSuccessSegment.results(1).delta_q);

    % The unreachable source 13 is evidence, not a successful q point. Its
    % failure barrier forces source 14 to restart with q_anchor.
    verifyEqual(testCase, failure.source_index, 13);
    verifyEqual(testCase, failure.t_ms, 200.0);
    verifyEqual(testCase, failure.reason, 'position_error_exceeds_tolerance');
    verifyEmpty(testCase, failure.q);
    verifyFalse(testCase, ismember(13, [ikResultSet.segments.source_indices]));

    verifyEqual(testCase, secondSuccessSegment.source_indices, 14);
    verifyEqual(testCase, secondSuccessSegment.t_ms, 300.0);
    verifySize(testCase, secondSuccessSegment.q_rad, [1, 5]);
    verifyEqual( ...
        testCase, ...
        secondSuccessSegment.results(1).seed_q, ...
        anchorResult.q, ...
        'AbsTol', 1e-12);
    verifyEmpty(testCase, secondSuccessSegment.results(1).delta_q);
end


